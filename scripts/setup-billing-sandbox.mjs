import {createPolar} from "@polar-sh/sdk/2026-10";
import {readFileSync,writeFileSync} from "node:fs";
const config=JSON.parse(readFileSync(".launch/sandbox.app.wrangler.json","utf8"));
if(config.name!=="blogstack-sandbox-app"||config.vars.POLAR_SERVER!=="sandbox"||config.d1_databases[0].database_name!=="blogstack-sandbox-db")throw new Error("The payment drill must remain isolated");
const saved=JSON.parse(readFileSync(".launch/polar.sandbox.secrets.json","utf8"));
const client=createPolar({accessToken:saved.POLAR_ACCESS_TOKEN,environment:"sandbox",timeout:20000});
const url=config.vars.API_URL+"/billing/webhooks/polar";
const main=JSON.parse(readFileSync("artifacts/polar-webhook.sandbox.json","utf8"));
let endpoint;
for await(const item of client.webhooks.iterListWebhookEndpoints())if(item.url===url)endpoint=item;
if(!endpoint)endpoint=await client.webhooks.createWebhookEndpoint({name:"BlogStack isolated sandbox billing",url,api_version:"2026-10",format:"raw",events:main.events});
if(!endpoint.enabled)endpoint=await client.webhooks.updateWebhookEndpoint(endpoint.id,{enabled:true});
const secretPath=".launch/sandbox.secrets.json";
const secrets=JSON.parse(readFileSync(secretPath,"utf8"));
secrets.POLAR_ACCESS_TOKEN=saved.POLAR_ACCESS_TOKEN;
secrets.POLAR_WEBHOOK_SECRET=endpoint.secret;
writeFileSync(secretPath,JSON.stringify(secrets,null,2)+"\n",{mode:0o600});
writeFileSync("artifacts/polar-webhook.sandbox-isolated.json",JSON.stringify({id:endpoint.id,url,environment:"sandbox",apiVersion:endpoint.api_version,events:endpoint.events},null,2)+"\n");
console.log("Isolated sandbox notification endpoint prepared; the live endpoint was not changed.");
